// Command listgen generates list_gen.go: the eager List[T] mirror of the
// Seq[T] operation set.
//
// It parses the package's Seq method declarations and emits one List
// method per Seq method, skipping:
//
//   - methods annotated //catena:seq-only (Once, Pull, ToChan, UntilDone,
//     Zip, Seq — meaningless or differently-shaped on an eager type), and
//   - names defined by hand in list.go (Append, with List semantics).
//
// Bodies delegate through the Seq implementation (the C15 conformance
// test in list_test.go asserts exactly that equivalence), except a small
// override set where eagerness buys exact preallocation or O(1) access.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// sourceFiles hold the Seq method set to mirror.
var sourceFiles = []string{"seq.go", "seq_map.go", "seq_terminal.go", "seq_fold.go", "seq_aggregate.go"}

// handWritten are List methods defined in list.go; never generate them.
var handWritten = []string{"Append"}

// overrides are generated with direct eager bodies instead of delegation.
var overrides = map[string]string{
	"Map": `func (l List[T]) Map[U any](f func(T) U) List[U] {
	if len(l) == 0 {
		return nil
	}
	out := make([]U, 0, len(l))
	for _, v := range l {
		out = append(out, f(v))
	}
	return List[U](out)
}`,
	"MapIndexed": `func (l List[T]) MapIndexed[U any](f func(int, T) U) List[U] {
	if len(l) == 0 {
		return nil
	}
	out := make([]U, 0, len(l))
	for i, v := range l {
		out = append(out, f(i, v))
	}
	return List[U](out)
}`,
	"Reversed": `func (l List[T]) Reversed() List[T] {
	if len(l) == 0 {
		return nil
	}
	out := make([]T, len(l))
	for i, v := range l {
		out[len(l)-1-i] = v
	}
	return List[T](out)
}`,
	"First": `func (l List[T]) First() (T, bool) {
	if len(l) == 0 {
		var zero T
		return zero, false
	}
	return l[0], true
}`,
	"Last": `func (l List[T]) Last() (T, bool) {
	if len(l) == 0 {
		var zero T
		return zero, false
	}
	return l[len(l)-1], true
}`,
	"ElementAt": `func (l List[T]) ElementAt(i int) (T, bool) {
	return l.Get(i)
}`,
	"Count": `func (l List[T]) Count() int {
	return len(l)
}`,
	"IsEmpty": `func (l List[T]) IsEmpty() bool {
	return len(l) == 0
}`,
	"Collect": `func (l List[T]) Collect() []T {
	if len(l) == 0 {
		return nil
	}
	return append([]T(nil), l...)
}`,
	"ToList": `func (l List[T]) ToList() List[T] {
	return l.Clone()
}`,
}

// fatal and formatSrc are seams so tests can exercise main's error paths
// and the format-failure branch without exiting the process.
var (
	fatal     = log.Fatal
	formatSrc = format.Source
)

func main() {
	formatted, err := generate(".")
	if err != nil {
		fatal(err)
		return
	}
	if err := os.WriteFile("list_gen.go", formatted, 0o644); err != nil {
		fatal(err)
	}
}

// generate builds the formatted list_gen.go content from the Seq method
// declarations found in dir.
func generate(dir string) ([]byte, error) {
	fset := token.NewFileSet()
	var out bytes.Buffer
	fmt.Fprintf(&out, `// Code generated by internal/gen/listgen. DO NOT EDIT.
//
// The eager List[T] mirror of the Seq[T] operation set. Semantics are
// identical to the Seq operator over AsSeq() — enforced by the C15
// conformance check in list_test.go. Chained List transforms allocate a
// full slice per stage, like Kotlin's List operations.

package catena
`)

	var names []string
	for _, file := range sourceFiles {
		f, err := parser.ParseFile(fset, filepath.Join(dir, file), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range f.Decls {
			d, ok := decl.(*ast.FuncDecl)
			if !ok || d.Recv == nil || !d.Name.IsExported() {
				continue
			}
			if recvBase(d) != "Seq" {
				continue
			}
			name := d.Name.Name
			if seqOnly(d) || slices.Contains(handWritten, name) {
				continue
			}
			names = append(names, name)
			out.WriteString("\n")
			if body, ok := overrides[name]; ok {
				fmt.Fprintf(&out, "// %s mirrors Seq.%s eagerly, implemented directly over the\n// backing slice rather than through the lazy pipeline.\n%s\n", name, name, body)
				continue
			}
			emitDelegation(&out, fset, d)
		}
	}

	// The registration manifest: list_test.go's completeness check reads
	// this to require a C15 case per generated method.
	fmt.Fprintf(&out, "\n// generatedListMethods is the manifest for the C15 conformance check.\nvar generatedListMethods = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&out, "\t%q,\n", n)
	}
	fmt.Fprintf(&out, "}\n")

	src := out.Bytes()
	if bytes.Contains(src, []byte("cmp.")) {
		src = bytes.Replace(src, []byte("package catena\n"), []byte("package catena\n\nimport \"cmp\"\n"), 1)
	}
	formatted, err := formatSrc(src)
	if err != nil {
		return nil, fmt.Errorf("generated code does not format: %w\n%s", err, src)
	}
	fmt.Printf("listgen: %d methods mirrored\n", len(names))
	return formatted, nil
}

func recvBase(d *ast.FuncDecl) string {
	t := d.Recv.List[0].Type
	for {
		switch r := t.(type) {
		case *ast.StarExpr:
			t = r.X
		case *ast.IndexExpr:
			t = r.X
		case *ast.IndexListExpr:
			t = r.X
		case *ast.Ident:
			return r.Name
		default:
			return ""
		}
	}
}

func seqOnly(d *ast.FuncDecl) bool {
	if d.Doc == nil {
		return false
	}
	for _, c := range d.Doc.List {
		if strings.HasPrefix(c.Text, "//catena:seq-only") {
			return true
		}
	}
	return false
}

func render(fset *token.FileSet, node any) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, node) // writing to a Buffer cannot fail
	return b.String()
}

// emitDelegation writes a List method that routes through the Seq
// implementation: FromSlice([]T(l)).M(args), collecting eagerly when the
// result is a Seq.
func emitDelegation(out *bytes.Buffer, fset *token.FileSet, d *ast.FuncDecl) {
	name := d.Name.Name

	typeParams := ""
	if d.Type.TypeParams != nil {
		var parts []string
		for _, f := range d.Type.TypeParams.List {
			var names []string
			for _, n := range f.Names {
				names = append(names, n.Name)
			}
			parts = append(parts, strings.Join(names, ", ")+" "+render(fset, f.Type))
		}
		typeParams = "[" + strings.Join(parts, ", ") + "]"
	}

	var params, args []string
	for _, f := range d.Type.Params.List {
		typ := render(fset, f.Type)
		var fieldNames []string
		for _, n := range f.Names {
			fieldNames = append(fieldNames, n.Name)
			if _, variadic := f.Type.(*ast.Ellipsis); variadic {
				args = append(args, n.Name+"...")
			} else {
				args = append(args, n.Name)
			}
		}
		params = append(params, strings.Join(fieldNames, ", ")+" "+typ)
	}

	var results []string
	seqElem := "" // set when the single result is Seq[X]
	if d.Type.Results != nil {
		for _, f := range d.Type.Results.List {
			typ := render(fset, f.Type)
			var fieldNames []string
			for _, n := range f.Names {
				fieldNames = append(fieldNames, n.Name)
			}
			prefix := ""
			if len(fieldNames) > 0 {
				prefix = strings.Join(fieldNames, ", ") + " "
			}
			results = append(results, prefix+typ)
		}
		if len(d.Type.Results.List) == 1 {
			if inner, ok := seqInstance(d.Type.Results.List[0].Type); ok {
				seqElem = render(fset, inner)
				results = []string{"List[" + seqElem + "]"}
			}
		}
	}
	resultStr := ""
	switch {
	case len(results) == 1 && !strings.Contains(results[0], " "):
		resultStr = " " + results[0]
	case len(results) > 0:
		resultStr = " (" + strings.Join(results, ", ") + ")"
	}

	call := fmt.Sprintf("FromSlice([]T(l)).%s(%s)", name, strings.Join(args, ", "))
	body := ""
	switch {
	case seqElem != "":
		body = fmt.Sprintf("\treturn List[%s](%s.Collect())", seqElem, call)
	case len(results) > 0:
		body = "\treturn " + call
	default:
		body = "\t" + call
	}

	fmt.Fprintf(out, "%sfunc (l List[T]) %s%s(%s)%s {\n%s\n}\n",
		mirrorDoc(name, resultStr), name, typeParams, strings.Join(params, ", "), resultStr, body)
}

// mirrorDoc is the doc comment for a delegated mirror. Most mirrors consume
// the list and hand back an eager value, but four of them mirror a Seq
// operator whose own result is lazy (Seq2 or Try). Saying "eagerly" and
// nothing else would leave a List user holding a lazy pipeline believing they
// held a finished value, so those name the crossing.
func mirrorDoc(name, resultStr string) string {
	lazy := ""
	switch {
	case strings.Contains(resultStr, "Seq2["):
		lazy = "Seq2"
	case strings.Contains(resultStr, "Try["):
		lazy = "Try"
	}
	if lazy == "" {
		return fmt.Sprintf("// %s mirrors Seq.%s eagerly.\n", name, name)
	}
	return fmt.Sprintf("// %s mirrors Seq.%s. The list is consumed eagerly, but the\n"+
		"// result is a lazy %s — one of the four List operators that cross back\n"+
		"// to lazy (see the List type).\n", name, name, lazy)
}

// seqInstance reports whether t is Seq[X], returning X.
func seqInstance(t ast.Expr) (ast.Expr, bool) {
	ix, ok := t.(*ast.IndexExpr)
	if !ok {
		return nil, false
	}
	id, ok := ix.X.(*ast.Ident)
	if !ok || id.Name != "Seq" {
		return nil, false
	}
	return ix.Index, true
}
